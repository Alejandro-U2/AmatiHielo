create table if not exists public.historial_prediccion_demanda (
  id bigint generated by default as identity primary key,
  producto_id bigint not null,
  producto_nombre text not null,
  periodo_inicio date not null,
  periodo_fin date not null,
  cantidad_predicha numeric(12, 2) not null check (cantidad_predicha >= 0),
  cantidad_real numeric(12, 2) check (cantidad_real is null or cantidad_real >= 0),
  creado_at timestamptz not null default now(),
  evaluado_at timestamptz,
  constraint historial_prediccion_demanda_periodo_valido check (periodo_fin >= periodo_inicio),
  constraint historial_prediccion_demanda_producto_periodo_key
    unique (producto_id, periodo_inicio, periodo_fin)
);

create index if not exists idx_historial_prediccion_demanda_pendiente
  on public.historial_prediccion_demanda (periodo_fin)
  where cantidad_real is null;

alter table public.historial_prediccion_demanda enable row level security;

drop policy if exists historial_prediccion_demanda_select_authenticated
  on public.historial_prediccion_demanda;
create policy historial_prediccion_demanda_select_authenticated
  on public.historial_prediccion_demanda
  for select to authenticated
  using (true);

drop policy if exists historial_prediccion_demanda_insert_authenticated
  on public.historial_prediccion_demanda;
create policy historial_prediccion_demanda_insert_authenticated
  on public.historial_prediccion_demanda
  for insert to authenticated
  with check (true);

drop policy if exists historial_prediccion_demanda_update_authenticated
  on public.historial_prediccion_demanda;
create policy historial_prediccion_demanda_update_authenticated
  on public.historial_prediccion_demanda
  for update to authenticated
  using (true)
  with check (true);

comment on table public.historial_prediccion_demanda is
  'Instantáneas de estimaciones semanales y sus ventas reales para medir el error histórico.';

-- Entrada de inventario: encabezado, detalle y registro transaccional.
create sequence if not exists public.entrada_inventario_numero_seq start 1;

create table if not exists public.entrada_inventario (
  id bigint generated by default as identity primary key,
  numero text not null unique default ('ENT-' || lpad(nextval('public.entrada_inventario_numero_seq')::text, 5, '0')),
  fecha date not null default current_date,
  tipo text not null default 'Compra',
  proveedor_id bigint not null references public.proveedor(id),
  numero_factura text not null,
  fecha_factura date,
  responsable text not null,
  observaciones text,
  documento_path text,
  estado text not null default 'Borrador' check (estado in ('Borrador', 'Confirmada')),
  subtotal numeric(14,2) not null default 0,
  total numeric(14,2) not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.entrada_inventario_detalle (
  id bigint generated by default as identity primary key,
  entrada_id bigint not null references public.entrada_inventario(id) on delete cascade,
  producto_id bigint not null references public.producto(id),
  unidad text not null default 'unidad',
  cantidad numeric(12,2) not null check (cantidad > 0),
  costo_unitario numeric(14,2) not null check (costo_unitario >= 0),
  lote text,
  fecha_vencimiento date,
  total_linea numeric(14,2) generated always as (cantidad * costo_unitario) stored
);

select setval(
  'public.entrada_inventario_numero_seq',
  greatest(
    coalesce((select max(nullif(regexp_replace(numero, '\D', '', 'g'), '')::bigint) from public.entrada_inventario), 0),
    (select last_value from public.entrada_inventario_numero_seq)
  ),
  true
);

create index if not exists idx_entrada_inventario_proveedor on public.entrada_inventario(proveedor_id);
create index if not exists idx_entrada_inventario_detalle_entrada on public.entrada_inventario_detalle(entrada_id);

insert into storage.buckets (id, name, public)
values ('entrada-inventario-documentos', 'entrada-inventario-documentos', false)
on conflict (id) do nothing;

drop policy if exists "entrada_documentos_insert_authenticated" on storage.objects;
create policy "entrada_documentos_insert_authenticated"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'entrada-inventario-documentos');
drop policy if exists "entrada_documentos_read_authenticated" on storage.objects;
create policy "entrada_documentos_read_authenticated"
  on storage.objects for select to authenticated
  using (bucket_id = 'entrada-inventario-documentos');

create or replace function public.registrar_entrada_inventario(
  p_proveedor_id bigint,
  p_numero_factura text,
  p_fecha date default current_date,
  p_fecha_factura date default null,
  p_responsable text default null,
  p_observaciones text default null,
  p_documento_path text default null,
  p_detalles jsonb default '[]'::jsonb,
  p_confirmar boolean default false
)
returns public.entrada_inventario
language plpgsql
security definer
set search_path = public
as $$
declare
  v_entrada public.entrada_inventario;
  v_detalle jsonb;
  v_producto public.producto%rowtype;
  v_cantidad numeric;
  v_costo numeric;
begin
  if not exists (select 1 from public.proveedor where id = p_proveedor_id and activo) then
    raise exception 'El proveedor seleccionado no existe o esta inactivo.';
  end if;
  if nullif(btrim(p_numero_factura), '') is null then
    raise exception 'El numero de factura es obligatorio.';
  end if;
  if jsonb_array_length(p_detalles) = 0 then
    raise exception 'La entrada debe incluir al menos un producto.';
  end if;

  insert into public.entrada_inventario (
    fecha, proveedor_id, numero_factura, fecha_factura, responsable,
    observaciones, documento_path, estado
  )
  values (
    coalesce(p_fecha, current_date), p_proveedor_id, btrim(p_numero_factura),
    p_fecha_factura, coalesce(nullif(btrim(p_responsable), ''), 'Sistema'),
    nullif(btrim(coalesce(p_observaciones, '')), ''), p_documento_path,
    case when p_confirmar then 'Confirmada' else 'Borrador' end
  )
  returning * into v_entrada;

  for v_detalle in select * from jsonb_array_elements(p_detalles)
  loop
    v_cantidad := (v_detalle->>'cantidad')::numeric;
    v_costo := (v_detalle->>'costo_unitario')::numeric;
    if v_cantidad <= 0 or v_costo < 0 then
      raise exception 'Cantidad y costo deben ser valores validos.';
    end if;
    insert into public.entrada_inventario_detalle (
      entrada_id, producto_id, unidad, cantidad, costo_unitario, lote, fecha_vencimiento
    )
    values (
      v_entrada.id, (v_detalle->>'producto_id')::bigint,
      coalesce(nullif(v_detalle->>'unidad', ''), 'unidad'), v_cantidad, v_costo,
      nullif(v_detalle->>'lote', ''), nullif(v_detalle->>'fecha_vencimiento', '')::date
    );
    update public.entrada_inventario
      set subtotal = subtotal + (v_cantidad * v_costo),
          total = total + (v_cantidad * v_costo)
      where id = v_entrada.id;

    if p_confirmar then
      select * into v_producto from public.producto
      where id = (v_detalle->>'producto_id')::bigint for update;
      if not found then raise exception 'No se encontro el producto seleccionado.'; end if;
      update public.producto
        set stock = stock + v_cantidad, costo_unitario = v_costo,
            precio_compra = v_costo, updated_at = now()
        where id = v_producto.id;
      insert into public.movimiento_inventario (
        producto_id, proveedor_id, tipo, cantidad, motivo, usuario
      )
      values (
        v_producto.id, p_proveedor_id, 'Entrada', v_cantidad,
        'Factura ' || btrim(p_numero_factura) || coalesce(' - ' || nullif(btrim(p_observaciones), ''), ''),
        coalesce(nullif(btrim(p_responsable), ''), 'Sistema')
      );
    end if;
  end loop;

  select * into v_entrada from public.entrada_inventario where id = v_entrada.id;
  return v_entrada;
end;
$$;

create table if not exists public.arqueo_caja (
  id bigint generated by default as identity primary key,
  periodo_inicio timestamptz not null,
  periodo_fin timestamptz not null,
  total_ventas numeric(12,2) not null default 0,
  total_efectivo numeric(12,2) not null default 0,
  total_transferencia numeric(12,2) not null default 0,
  transacciones integer not null default 0,
  usuario text,
  confirmado_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  constraint arqueo_caja_periodo_valido check (periodo_fin > periodo_inicio),
  constraint arqueo_caja_periodo_unico unique (periodo_inicio, periodo_fin)
);

create index if not exists idx_arqueo_caja_periodo_fin
  on public.arqueo_caja(periodo_fin desc);

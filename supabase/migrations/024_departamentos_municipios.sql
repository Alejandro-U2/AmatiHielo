-- Ubicacion en profiles (departamento y municipio).
alter table public.profiles
  add column if not exists departamento_id bigint references public.departamento(id),
  add column if not exists municipio_id bigint references public.municipio(id);

-- Backfill de usuarios existentes: Departamento de Guatemala / Municipio de Guatemala.
update public.profiles p
set departamento_id = d.id
from public.departamento d
where p.departamento_id is null
  and d.nombre = 'Guatemala';

update public.profiles p
set municipio_id = m.id
from public.municipio m
join public.departamento d on d.id = m.departamento_id
where p.municipio_id is null
  and d.nombre = 'Guatemala'
  and m.nombre = 'Guatemala';

alter table public.profiles
  alter column departamento_id set not null,
  alter column municipio_id set not null;

create index if not exists idx_profiles_departamento_id on public.profiles (departamento_id);
create index if not exists idx_profiles_municipio_id on public.profiles (municipio_id);
create index if not exists idx_municipio_departamento_id on public.municipio (departamento_id);


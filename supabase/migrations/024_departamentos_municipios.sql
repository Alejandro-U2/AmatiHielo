-- Catalogo de departamentos y municipios de Guatemala.
-- Agrega la ubicacion (departamento y municipio) al perfil de usuario.
-- El pais es fijo (Guatemala) y no se almacena como columna.

create table if not exists public.departamento (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  nombre text not null unique,
  descripcion text,
  activo boolean not null default true,
  es_sistema boolean not null default true,
  orden integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.municipio (
  id bigint generated by default as identity primary key,
  departamento_id bigint not null references public.departamento(id),
  nombre text not null,
  descripcion text,
  activo boolean not null default true,
  es_sistema boolean not null default true,
  orden integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (departamento_id, nombre)
);

